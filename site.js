/* скелетон обложек. Правило запуска: как только обложка видна в окне целиком и её изображение загружено — скелетон начинает исчезать и идёт отсчёт времени.
   Время одинаково на всех обложках: пауза .5 с, затем 1,7 с на смену зон (у ATS — одна длинная фаза) и 1,3 с на растворение, всё делённое на скорость ×3.
   При prefers-reduced-motion скелетон не показывается. */
(() => {
  const covers = [...document.querySelectorAll('.kcover')];
  if (!covers.length) return;
  const SPEED = '3';
  const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
  const ready = c => [...c.querySelectorAll('img')].every(i => i.complete && i.naturalWidth > 0);
  const inView = c => {
    const r = c.getBoundingClientRect();
    const panel = c.closest('.kcard') && c.closest('.kcard').querySelector('.kcard__panel');
    const bottom = panel ? Math.min(r.bottom, panel.getBoundingClientRect().top) : r.bottom;   // нижний край обложки перекрыт панелью с текстом — считаем видимой только часть выше неё
    const h = bottom - r.top;
    if (h <= 0) return false;
    const seen = Math.min(bottom, innerHeight) - Math.max(r.top, 0);
    return seen >= Math.min(h, innerHeight) * .92;
  };
  const check = () => covers.forEach(c => {
    if (c.classList.contains('is-play')) return;
    if (inView(c) && ready(c)) c.classList.add('is-play');
  });
  let raf = 0;
  const schedule = () => { if (!raf) raf = requestAnimationFrame(() => { raf = 0; check(); }); };
  const arm = () => covers.forEach(c => {
    c.dataset.anim = 'b';
    c.style.setProperty('--sp', SPEED);
    c.classList.remove('is-play');
    c.classList.toggle('is-armed', !reduce);
  });
  window.__coverAnim = {
    speed: () => SPEED,
    replay: () => { arm(); void covers[0].offsetWidth; covers[0].closest('.case').scrollIntoView({ behavior: 'smooth', block: 'center' }); setTimeout(check, 50); }
  };
  if (reduce) return;
  arm();
  covers.forEach(c => c.querySelectorAll('img').forEach(i => i.addEventListener('load', schedule)));
  addEventListener('scroll', schedule, { passive: true });
  addEventListener('resize', schedule);
  addEventListener('load', schedule);
  schedule();
})();

/* плашка контактов (Б): вниз — прячем, вверх на 60 px — показываем, у верха страницы и при фокусе внутри — всегда видна */
(() => {
  const bar = document.querySelector('.sidebar__links');
  if (!bar) return;
  const TOP = 500, DOWN = 12, UP = 60;
  let last = scrollY, down = 0, up = 0, raf = 0;
  const tuck = on => bar.classList.toggle('is-tucked', on);
  const tick = () => {
    raf = 0;
    const y = Math.max(0, scrollY), dy = y - last;
    last = y;
    if (y < TOP || bar.matches(':focus-within')) { down = up = 0; tuck(false); return; }
    if (dy > 0) { down += dy; up = 0; if (down > DOWN) tuck(true); }
    else if (dy < 0) { up -= dy; down = 0; if (up > UP) tuck(false); }
  };
  addEventListener('scroll', () => { if (!raf) raf = requestAnimationFrame(tick); }, { passive: true });
  bar.addEventListener('focusin', () => tuck(false));
})();

/* ===== зум изображений в шторке (пока только ATS): клик по картинке — крупно; закрытие: клик вне картинки, × или Esc ===== */
(() => {
  const ZOOM_SLUGS = null; /* null — зум во всех кейсах; массив slug — только в перечисленных */
  let box = null;
  const close = () => { if (!box) return; box.remove(); box = null; };
  document.addEventListener('click', e => {
    if (box) { if (!e.target.closest('.zoom__img')) close(); return; }
    const img = e.target.closest('.sheet__in figure img');
    const inner = img && img.closest('.sheet__in');
    if (!img || !inner || (ZOOM_SLUGS && !ZOOM_SLUGS.includes(inner.dataset.slug)) || img.closest('.ba')) return;
    box = document.createElement('div');
    box.className = 'zoom'; box.setAttribute('role', 'dialog'); box.setAttribute('aria-label', 'Увеличенное изображение');
    box.innerHTML = `<button type="button" class="zoom__x" aria-label="Закрыть">×</button><img class="zoom__img" src="${img.currentSrc || img.src}" alt="${esc(img.alt || '')}">`;
    document.body.appendChild(box);
    box.querySelector('.zoom__x').focus({ preventScroll: true });
  });
  document.addEventListener('keydown', e => { if (box && e.key === 'Escape') { e.stopImmediatePropagation(); close(); } }, true);
  document.addEventListener('mouseover', e => {
    const img = e.target.closest && e.target.closest('.sheet__in figure img'); if (!img) return;
    const inner = img.closest('.sheet__in'); img.style.cursor = inner && (!ZOOM_SLUGS || ZOOM_SLUGS.includes(inner.dataset.slug)) && !img.closest('.ba') ? 'zoom-in' : '';
  });
})();
