/* ============================ ТИПОГРАФИКА: неразрывные пробелы ============================
   Правило для всего сайта (главная, карточки, «Опыт», шторка): после предлогов, союзов и частиц — неразрывный пробел (чтобы «и», «в», «на» не висели в конце строки);
   перед тире и стрелкой, между числом и единицей (15 %, 30+ млн ₽). Работает над готовым DOM, данные в CASES не меняются. */
(() => {
  const SHORT = 'в|во|к|ко|с|со|о|об|обо|у|на|по|за|из|от|до|не|ни|но|а|и|я|же|бы|ли|для|при|без|над|под|про|или|как|что|то';
  const RULES = [
    [new RegExp('(?<![\\p{L}\\p{N}\\-\u2011])(' + SHORT + ') ', 'giu'), '$1\u00A0'],
    [/ +(—|–|→)/g, '\u00A0$1'],
    [/(→) +/g, '$1\u00A0'],
    [/(\d\+?) (%|₽|млн|млрд|тыс\.?|мин|сек|мс)(?![\p{L}])/gu, '$1\u00A0$2'],
    [/(\d\+?) (?=\p{L})/gu, '$1\u00A0'],
    [/(млн|млрд|тыс\.?) (₽)/g, '$1\u00A0$2']
  ];
  const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'CODE', 'PRE', 'NOSCRIPT']);
  const fix = s => RULES.reduce((a, [re, to]) => a.replace(re, to), s);
  const text = n => { const v = fix(n.nodeValue); if (v !== n.nodeValue) n.nodeValue = v; };
  const run = root => {
    if (root.nodeType === 3) return text(root);
    if (root.nodeType !== 1 || SKIP.has(root.nodeName) || root.closest('svg')) return;
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode: n => SKIP.has(n.parentNode.nodeName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT });
    const list = []; for (let n; (n = w.nextNode());) list.push(n);
    list.forEach(text);
  };
  run(document.body);
  new MutationObserver(ms => ms.forEach(m => m.addedNodes.forEach(run))).observe(document.body, { childList: true, subtree: true });
})();

