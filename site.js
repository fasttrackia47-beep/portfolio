function armMissing(root) {
  root.querySelectorAll('img[data-ph]').forEach(img => {
    const drop = () => img.closest('.frame, .kcard__media, .case__media figure')?.remove();
    if (img.complete && img.naturalWidth === 0) drop(); else img.addEventListener('error', drop, { once: true });
  });
  /* видео-ролики (.mp4): убираем, если файла нет; играем только в зоне видимости */
  const vids = root.querySelectorAll('video[data-ph]');
  if (!vids.length) return;
  const io = 'IntersectionObserver' in window ? new IntersectionObserver(es => es.forEach(e => {
    if (e.isIntersecting) e.target.play().catch(() => {}); else e.target.pause();
  }), { threshold: .25 }) : null;
  vids.forEach(v => {
    v.addEventListener('error', () => v.closest('.case__media figure')?.remove(), { once: true });
    if (io) io.observe(v);
  });
}
