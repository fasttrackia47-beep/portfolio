/* ============================ РЯБЬ ПО ВОДЕ (hero, B) ============================
   Идея с kirill.si: точечное поле; по клику от точки касания расходятся круги, точки в кольце «вспухают».
   Цвет — #EBF0F5 (как плашка «Слава»), пик прозрачности 50%. Не работает при prefers-reduced-motion. */
(() => {
  const hero = document.querySelector('.hero');
  if (!hero) return;
  const cv = document.createElement('canvas');
  cv.className = 'ripple'; cv.setAttribute('aria-hidden', 'true');
  hero.prepend(cv);
  const ctx = cv.getContext('2d');
  const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
  const STEP = 14, SPEED = 364, RING = 110, LIFE = 3.8;   // медленнее на 30%, кольцо толще
  let W = 0, H = 0, dpr = 1, ripples = [], raf = 0, color = '235,240,245', peak = .5;
  const size = () => {
    const top = hero.getBoundingClientRect().top + scrollY;   // холст начинается от верха страницы (над фото)
    cv.style.top = -top + 'px'; cv.style.height = (top + hero.offsetHeight + 60) + 'px';
    const r = cv.getBoundingClientRect(); dpr = Math.min(devicePixelRatio || 1, 2);
    W = r.width; H = r.height; cv.width = W * dpr; cv.height = H * dpr; ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    draw(performance.now());
  };
  const draw = now => {
    ctx.clearRect(0, 0, W, H);
    const cs = getComputedStyle(document.documentElement);
    const c = (cs.getPropertyValue('--ripple-rgb') || '').trim(); if (c) color = c;
    const a = parseFloat(cs.getPropertyValue('--ripple-a')); if (a) peak = a;
    ripples = ripples.filter(r => (now - r.t0) / 1000 < LIFE);
    const cols = Math.ceil(W / STEP) + 1, rows = Math.ceil(H / STEP) + 1;
    for (let i = 0; i < cols; i++) for (let k = 0; k < rows; k++) {
      const x = i * STEP, y = k * STEP;
      let v = 0;
      for (const r of ripples) {
        const age = (now - r.t0) / 1000, d = Math.hypot(x - r.x, y - r.y), dl = d - SPEED * age;
        v += Math.exp(-(dl * dl) / (RING * RING)) * Math.exp(-age / 1.6);
      }
      if (v < .02) continue;
      const rad = Math.min(STEP * .5, .6 + v * STEP * .55);
      ctx.fillStyle = `rgba(${color},${Math.min(1, v) * peak * 2})`;
      ctx.beginPath(); ctx.arc(x, y, rad, 0, 6.2832); ctx.fill();
    }
    if (ripples.length) raf = requestAnimationFrame(draw); else raf = 0;
  };
  const spawn = (cx, cy) => {
    if (reduce) return;
    const r = cv.getBoundingClientRect();
    ripples.push({ x: cx - r.left, y: cy - r.top, t0: performance.now() });
    if (!raf) raf = requestAnimationFrame(draw);
  };
  hero.addEventListener('click', e => {
    const li = e.target.closest('.anchors li');
    if (li) { const b = li.querySelector('.anchors__ico').getBoundingClientRect(); spawn(b.left + b.width / 2, b.top + b.height / 2); }
    else if (!e.target.closest('a,button')) spawn(e.clientX, e.clientY);
  });
  addEventListener('resize', size);
  size();
  setTimeout(() => { const p = document.querySelector('.sidebar__photo'); if (p) { const b = p.getBoundingClientRect(); spawn(b.left + b.width / 2, b.top + b.height / 2); } }, 900);
})();

/* ============================ ФУТЕР: чёрная плашка «заезжает» по скроллу ============================
   --p (0…1) = прогресс внутри «взлётной полосы» футера; тёмный слой открывается снизу вверх. */
(() => {
  const upd = () => [...document.querySelectorAll('.fvx')].forEach(el => {
    const run = el.querySelector('.fvx__run'); if (!run) return;
    const r = run.getBoundingClientRect(), H = el.querySelector('.fvx__stick').offsetHeight, total = r.height - H;
    const p = Math.min(1, Math.max(0, (innerHeight - H - r.top) / total));
    el.style.setProperty('--p', p.toFixed(4));
  });
  /* опыт «замирает» на время заезда плашки средствами CSS (position:sticky) — без JS-сдвигов, поэтому без дрожания.
     top = высота экрана − высота плашки − зазор − высота блока опыта; пересчёт только при ресайзе/раскрытии строк. */
  const pin = () => {
    const xp = document.querySelector('.exp--v6'), st = [...document.querySelectorAll('.fvx__stick')].find(e => e.offsetHeight);
    if (!xp || !st || !st.offsetHeight) return;
    const gap = parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--fgap')) || 0;
    xp.style.top = (innerHeight - st.offsetHeight - gap - xp.offsetHeight) + 'px';
  };
  addEventListener('scroll', upd, { passive: true }); addEventListener('resize', () => { upd(); pin(); }); upd(); pin();
  const xpEl = document.querySelector('.exp--v6'); if (xpEl && window.ResizeObserver) new ResizeObserver(pin).observe(xpEl);
})();


